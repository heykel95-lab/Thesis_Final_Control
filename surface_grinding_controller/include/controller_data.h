/// Stores thread-safe operator requests consumed by the real-time loop.
struct KeyboardSignals {
  std::atomic<bool> stop_requested{false};      // Requests a controlled stop.
  std::atomic<bool> proceed_requested{false};   // Continues after pose recapture.
  std::atomic<bool> guide_requested{false};     // Requests manual guidance.
  std::atomic<char> guidance_menu_key{0};       // Selected guidance action key.
  std::atomic<bool> guided_hold_selector_pending{false}; // Waits for s, h, or t.
  std::atomic<bool> operator_hold_continue{false}; // Continues an operator-hold state.
  std::atomic<bool> menu_requested{true};       // Grants the menu exclusive stdin access.

  // Defining live nullspace requests. NaN or -1 indicates an empty slot.
  std::atomic<double> nullspace_damping_request{
      std::numeric_limits<double>::quiet_NaN()}; // [N m s/rad].
  std::atomic<double> nullspace_sigma_gain_request{
      std::numeric_limits<double>::quiet_NaN()}; // [N m].
  std::atomic<double> nullspace_probe_step_deg_request{
      std::numeric_limits<double>::quiet_NaN()}; // Probe step [deg].
  std::atomic<int> nullspace_mode_request{-1};   // Encoded NullspaceMode [-].

  std::atomic<char> run_mode_request{0}; // s = sequence; t = contact-impedance hold.

  // Defining live contact establishment-gain requests in surface-axis order.
  std::array<std::atomic<double>, 3> contact_establishment_kp_request; // Kp [N/m].
  std::array<std::atomic<double>, 3> contact_establishment_kr_request; // KR [N m/rad].

  // Defining live compliance-center requests.
  std::array<std::atomic<double>, 3> contact_establishment_compliance_center_mm_request; // EE [mm].
  // r_c = p_C - p_TCP, in surface axes.
  std::array<std::atomic<double>, 3> contact_establishment_rc_mm_request; // [t1,t2,n] [mm].

  // Defining tool-axis tilt for the next sequence [tangent1,tangent2] [deg].
  std::array<std::atomic<double>, 2> contact_establishment_tilt_deg_request;

  /// Initializes each numerical request slot with the empty NaN marker.
  KeyboardSignals() {
    const double none = std::numeric_limits<double>::quiet_NaN();
    for (int i = 0; i < 3; ++i) {
      contact_establishment_kp_request[i].store(none);
      contact_establishment_kr_request[i].store(none);
      contact_establishment_compliance_center_mm_request[i].store(none);
      contact_establishment_rc_mm_request[i].store(none);
    }
    for (int i = 0; i < 2; ++i) {
      contact_establishment_tilt_deg_request[i].store(none);
    }
  }
};

/// Stores the impedance matrices derived from the controller configuration.
struct StateImpedanceGains {
  Mat3 R_base_surface = Mat3::Identity(); // Surface frame expressed in base [-].

  Mat3 Kp_approach = Mat3::Zero(); // Approach translational stiffness [N/m].
  Mat3 Dp_approach = Mat3::Zero(); // Approach translational damping [N s/m].
  Mat3 KR_approach = Mat3::Zero(); // Approach rotational stiffness [N m/rad].
  Mat3 DR_approach = Mat3::Zero(); // Approach rotational damping [N m s/rad].

  Vec3 contact_establishment_Kp_active_diag = Vec3::Zero(); // Selected contact establishment stiffness diagonal [N/m].
  Vec3 contact_establishment_Dp_active_diag = Vec3::Zero(); // Selected contact establishment damping diagonal [N s/m].
  Mat3 Kp_contact_establishment = Mat3::Zero(); // Contact translational stiffness [N/m].
  Mat3 Dp_contact_establishment = Mat3::Zero(); // Contact translational damping [N s/m].
  Mat3 KR_contact_establishment = Mat3::Zero(); // Contact rotational stiffness [N m/rad].
  Mat3 DR_contact_establishment = Mat3::Zero(); // Contact rotational damping [N m s/rad].

  Mat3 Kp_hold = Mat3::Zero(); // Hold translational stiffness [N/m].
  Mat3 Dp_hold = Mat3::Zero(); // Hold translational damping [N s/m].
  Mat3 KR_hold = Mat3::Zero(); // Hold rotational stiffness [N m/rad].
  Mat3 DR_hold = Mat3::Zero(); // Hold rotational damping [N m s/rad].

  Vec3 operator_hold_Kp_active_diag = Vec3::Zero(); // Selected hold stiffness [N/m].
  Vec3 operator_hold_Dp_active_diag = Vec3::Zero(); // Selected hold damping [N s/m].
  Vec3 operator_hold_KR_active_diag = Vec3::Zero(); // Selected hold stiffness [N m/rad].
  Vec3 operator_hold_DR_active_diag = Vec3::Zero(); // Selected hold damping [N m s/rad].
  Mat3 Kp_operator_hold = Mat3::Zero(); // Hold-state translational stiffness [N/m].
  Mat3 Dp_operator_hold = Mat3::Zero(); // Hold-state translational damping [N s/m].
  Mat3 KR_operator_hold = Mat3::Zero(); // Hold-state rotational stiffness [N m/rad].
  Mat3 DR_operator_hold = Mat3::Zero(); // Hold-state rotational damping [N m s/rad].
};

/// Stores damping matrices evaluated or selected at state entry.
struct StateDampingCache {
  bool approach_computed = false; // Indicates initialized approach damping.
  bool contact_establishment_computed = false;    // Indicates initialized contact establishment damping.
  bool hold_computed = false;     // Indicates initialized hold damping.
  bool operator_hold_computed = false;    // Indicates initialized hold-state damping.

  Mat3 Dp_approach = Mat3::Zero(); // [N s/m].
  Mat3 DR_approach = Mat3::Zero(); // [N m s/rad].
  Mat3 Dp_contact_establishment = Mat3::Zero();    // [N s/m].
  Mat3 DR_contact_establishment = Mat3::Zero();    // [N m s/rad].
  Mat3 Dp_hold = Mat3::Zero();     // [N s/m].
  Mat3 DR_hold = Mat3::Zero();     // [N m s/rad].
  Mat3 Dp_operator_hold = Mat3::Zero();    // [N s/m].
  Mat3 DR_operator_hold = Mat3::Zero();    // [N m s/rad].

  // Defining the damping diagonals reported in each state frame.
  bool contact_establishment_damping_valid = false;
  Vec3 contact_establishment_Dp_used = Vec3::Zero();    // [N s/m].
  Vec3 contact_establishment_DR_used = Vec3::Zero();    // [N m s/rad].
  bool approach_damping_valid = false;
  Vec3 approach_Dp_used = Vec3::Zero(); // [N s/m].
  Vec3 approach_DR_used = Vec3::Zero(); // [N m s/rad].
  bool operator_hold_damping_valid = false;
  Vec3 operator_hold_Dp_used = Vec3::Zero();    // [N s/m].
  Vec3 operator_hold_DR_used = Vec3::Zero();    // [N m s/rad].
  bool hold_damping_valid = false;
  Vec3 hold_Dp_used = Vec3::Zero();     // [N s/m].
  Vec3 hold_DR_used = Vec3::Zero();     // [N m s/rad].
};

/// Stores the final state and chronological samples returned by one run.
struct RunResult {
  bool descend_failed = false;        // Indicates an unsuccessful surface approach.
  Vec7 q_start = Vec7::Zero();        // Joint posture at run start [rad].
  Vec7 final_q = Vec7::Zero();        // Joint posture at run end [rad].
  Vec3 final_p_d = Vec3::Zero();      // Final desired TCP position [m].
  Vec3 final_p_EE = Vec3::Zero();     // Final measured TCP position [m].
  Vec3 final_e_p = Vec3::Zero();      // Final translational error [m].
  Vec3 final_e_R = Vec3::Zero();      // Final orientation error [rad].
  std::vector<LogData> log;           // Chronological control samples.
};
