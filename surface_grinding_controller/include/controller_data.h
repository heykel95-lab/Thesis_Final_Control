#pragma once

#include "controller_config.h"

/// Stores the equivalent point-force disturbance and its joint-space torque.
struct AutomaticDisturbance {
  double scale = 0.0;             // Time-dependent force scale [-].
  double torque_scale = 1.0;      // Torque-limit scale [-].
  Vec3 point_base = Vec3::Zero(); // Force application point in base frame [m].
  Vec3 force_base = Vec3::Zero(); // Applied force in base frame [N].
  Vec7 tau = Vec7::Zero();        // Equivalent joint torque [N m].
};

/// Stores one chronological sample of the controller state and command.
/// Cartesian positions, forces, and moments are expressed in the base frame
/// unless a field name states another frame.
struct LogData {
  double time;          // Time from run start [s].
  int state;            // Encoded ControlState value [-].
  int nullspace_mode;   // Encoded NullspaceMode value [-].

  Vec3 p_EE;                    // Measured TCP position [m].
  Vec3 p_d;                     // Desired TCP position [m].
  Vec3 tool_contact_point;      // Measured tool-feature position [m].
  Vec3 first_contact_tcp;       // TCP position at first contact [m].
  Vec3 first_contact_point;     // Tool-feature position at first contact [m].
  Vec3 edge_target;             // Desired tool-feature position [m].
  Vec3 tool_contact_offset_ee;  // Feature offset in EE frame [m].
  Vec3 p_CoC;   // Centre of compliance, p_TCP + r_c [m]. Equals p_EE when the
                // lever is zero, so the centre is the TCP in that case.
  Vec3 r_eff;   // Lever the contact force acts through, p_contact - p_CoC [m].

  Vec3 e_p;  // Translational error p_d - p_EE [m].
  Vec3 e_R;  // Orientation error in base frame [rad].
  Vec3 angular_deviation_surface; // Deviation in [tangent1,tangent2,normal] [rad].
  double angular_deviation;       // Residual tool-to-plane deviation [rad].
  double t_align;                 // Time from first contact at which the
                                  // deviation first fell inside the tolerance
                                  // and stayed there [s]; negative until then.

  Vec3 pdot;    // Measured TCP linear velocity [m/s].
  Vec3 pdot_d;  // Desired TCP linear velocity [m/s].
  Vec3 omega;   // Measured angular velocity in base frame [rad/s].

  Vec3 f;                    // Commanded Cartesian force [N].
  Vec3 m;                    // Commanded Cartesian moment [N m].
  Vec3 external_force;       // O_F_ext_hat_K force component [N].
  Vec3 external_moment;      // O_F_ext_hat_K moment component [N m].
  Vec3 external_force_K_base;  // K_F_ext_hat_K force rotated into base axes [N].
  Vec3 external_moment_K_base; // K_F_ext_hat_K moment rotated into base axes [N m].
  Vec3 r_K_TCP_base;         // Offset p_K - p_TCP in base axes [m].
  Vec3 setup_Dp_used;        // Active setup damping in [t1,t2,n] [N s/m].
  Vec3 setup_DR_used;        // Active setup damping in [t1,t2,n] [N m s/rad].
  Vec3 contact_force_bias;   // External-force bias captured at contact [N].
  Vec3 contact_moment_bias;  // External-moment bias captured at contact [N m].
  double push;               // Virtual surface penetration [m].

  AutomaticDisturbance disturbance; // Applied disturbance state.

  double tau_nullspace_norm; // Nullspace-torque Euclidean norm [N m].
  double nullspace_damping;  // Active damping coefficient [N m s/rad].
  Vec7 tau_cmd;              // Final commanded joint torque [N m].
};

