// Defines the commands, gain matrices, shared signals, reports, and log records
// exchanged between the control, interface, and reporting modules.
#pragma once

#include "controller_config.h"

/// Stores the equivalent point-force disturbance and its joint-space torque.
struct AutomaticDisturbance {
  double scale = 0.0;             // Time-dependent force scale [-].
  double torque_scale = 1.0;      // Torque-limit scale [-].
  Vec3 point_base = Vec3::Zero(); // Force application point in base frame [m].
  Vec3 force_base = Vec3::Zero(); // Applied force in base frame [N].
  Vec7 tau = Vec7::Zero();        // Equivalent joint torque [N m].
};

/// Stores one chronological sample of the controller state and command.
/// Cartesian positions, forces, and moments are expressed in the base frame
/// unless a field name states another frame.
struct LogData {
  double time;          // Time from run start [s].
  int phase;            // Encoded ControlPhase value [-].
  int nullspace_mode;   // Encoded NullspaceMode value [-].

  Vec3 p_EE;                    // Measured TCP position [m].
  Vec3 p_d;                     // Desired TCP position [m].
  Vec3 tool_contact_point;      // Measured tool-feature position [m].
  Vec3 first_contact_tcp;       // TCP position at first contact [m].
  Vec3 first_contact_point;     // Tool-feature position at first contact [m].
  Vec3 edge_target;             // Desired tool-feature position [m].
  Vec3 tool_contact_offset_ee;  // Feature offset in EE frame [m].

  Vec3 e_p;  // Translational error p_d - p_EE [m].
  Vec3 e_R;  // Orientation error in base frame [rad].
  Vec3 alignment_error_surface; // Tool-axis error in [tangent1,tangent2,normal] [rad].
  double alignment_angle;       // Residual tool-axis misalignment [rad].

  Vec3 pdot;    // Measured TCP linear velocity [m/s].
  Vec3 pdot_d;  // Desired TCP linear velocity [m/s].
  Vec3 omega;   // Measured angular velocity in base frame [rad/s].

  Vec3 f;                    // Commanded Cartesian force [N].
  Vec3 m;                    // Commanded Cartesian moment [N m].
  Vec3 external_force;       // Estimated external force [N].
  Vec3 external_moment;      // Estimated external moment [N m].
  Vec3 contact_force_bias;   // External-force bias captured at contact [N].
  Vec3 contact_moment_bias;  // External-moment bias captured at contact [N m].
  double push;               // Virtual surface penetration [m].

  AutomaticDisturbance disturbance; // Applied disturbance state.

  double tau_nullspace_norm; // Nullspace-torque Euclidean norm [N m].
  double nullspace_damping;  // Active damping coefficient [N m s/rad].
  Vec7 tau_cmd;              // Final commanded joint torque [N m].
};

// ---------------------------------------------------------------------------
// Commands and phase reports
// ---------------------------------------------------------------------------

/// Defines the translational reference generated by the active phase.
struct DesiredTranslationCommand {
  Vec3 p_d;     // Desired TCP position in base frame [m].
  Vec3 pdot_d;  // Desired TCP linear velocity in base frame [m/s].
};

/// Stores the diagonal Cartesian inertia estimate in the selected task frame.
struct CartesianInertiaEstimate {
  Vec3 translational = Vec3::Ones(); // Translational inertia [kg].
  Vec3 rotational = Vec3::Ones();    // Rotational inertia [kg m^2].
  bool valid = false;                // Indicates a valid finite estimate.
};

/// Stores the state, wrench, and active gains captured when setup ends.
struct SetupReport {
  // Defining the phase termination and measured wrench changes.
  bool stopped_on_moment = false;   // true when the moment threshold ends setup.
  double phase_time = 0.0;          // Setup duration [s].
  double force_delta_norm = 0.0;    // Contact-force change norm [N].
  double moment_delta_norm = 0.0;   // Contact-moment change norm [N m].

  // Defining the final pose and contact wrench in the base frame.
  Vec3 p_EE = Vec3::Zero();                 // Final TCP position [m].
  Mat3 R_EE = Mat3::Identity();             // Final EE orientation [-].
  Vec3 tool_contact_point = Vec3::Zero();   // Final tool-feature position [m].
  Vec3 external_force = Vec3::Zero();       // Final external force [N].
  Vec3 contact_moment = Vec3::Zero(); // Moment at the contact point [N m].

  // Defining the first-contact reference in the base frame.
  Vec3 first_contact_tcp = Vec3::Zero();    // TCP position at contact [m].
  Vec3 first_contact_point = Vec3::Zero();  // Tool-feature position at contact [m].
  Mat3 R_contact_start = Mat3::Identity();  // EE orientation at contact [-].
  Vec3 contact_force_bias = Vec3::Zero();   // Captured force bias [N].

  // Defining the active setup impedance in base coordinates.
  Mat3 Kp = Mat3::Zero(); // Translational stiffness [N/m].
  Mat3 Dp = Mat3::Zero(); // Translational damping [N s/m].
  Mat3 KR = Mat3::Zero(); // Rotational stiffness [N m/rad].
  Mat3 DR = Mat3::Zero(); // Rotational damping [N m s/rad].
};

